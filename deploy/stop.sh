#!/bin/bash
# ===========================================================================
# 停止 PPSD 后端
#
# 用法： bash ~/PPSD/stop.sh
#
# 为什么模式写成 "[n]ode" 而不是 "node"：
#   pkill -f 是拿"模式"去匹配每个进程的完整命令行。
#   如果直接写 pkill -f "node src/server.js"，这条命令自己的命令行里
#   也含这串字，就可能把发起命令的 shell 也一起杀掉（ssh 会话直接断开）。
#   把第一个字母放进方括号里（正则里 [n] 就等于 n），命令行里出现的是字面
#   "[n]ode ..."，模式却仍然只匹配真正的 node 进程 —— 自己匹配不到自己。
# ===========================================================================
if pkill -f "[n]ode src/server.js"; then
    echo "已停止 PPSD 后端"
else
    echo "没有正在运行的 PPSD 后端（或已经停了）"
fi
