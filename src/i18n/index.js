/**
 * 极简 i18n —— 英文为默认语言，右上角可切到简体中文。
 *
 * 为什么不用 vue-i18n：
 *   这个站只有两种语言、一套文案，vue-i18n 的复数规则 / 插值 / 懒加载 / 命名空间
 *   一个都用不上。用一个 ref + 一张字典表就够了，而且读代码的人一眼能看懂。
 *   将来真需要复杂能力时，换成 vue-i18n 的迁移成本也就是把 t() 换个来源。
 *
 * 用法（组件里）：
 *   import { t, locale, setLocale } from '../i18n'
 *   模板里直接 {{ t('nav.home') }}
 *   t 内部读的是响应式 ref，所以切语言时所有用到它的地方会自动重渲染。
 */
import { ref, computed } from 'vue'

const STORAGE_KEY = 'ppsd.locale'
const SUPPORTED = ['en', 'zh']

/** 从 localStorage 取上次选的语言；默认英文（导师要求数据库以英文为主） */
function initialLocale() {
    try {
        const saved = localStorage.getItem(STORAGE_KEY)
        if (saved && SUPPORTED.includes(saved)) return saved
    } catch {
        /* 隐私模式下 localStorage 可能抛错，忽略即可 */
    }
    return 'en'
}

export const locale = ref(initialLocale())

export function setLocale(next) {
    if (!SUPPORTED.includes(next)) return
    locale.value = next
    try {
        localStorage.setItem(STORAGE_KEY, next)
    } catch {
        /* 存不了就算了，不影响本次会话 */
    }
    // 让 <html lang> 跟着变，屏幕阅读器和浏览器断词规则都依赖它
    document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en'
}

export const isZh = computed(() => locale.value === 'zh')

